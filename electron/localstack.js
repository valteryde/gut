const composeArgs = (proj = MANAGED) => [
  'compose', '-p', proj, '-f', composeFile(proj),
  // A missing .env must not break ps/restart — `up` reports it anyway.
  ...(fs.existsSync(envFile(proj)) ? ['--env-file', envFile(proj)] : []),
];

// The gut desktop container, whichever compose project owns it — a running
// one wins over created/exited. Lifecycle commands target this project.
async function desktopContainer() {
  const r = await run('docker',
    ['ps', '-a', '--format', '{{.Names}} {{.State}}']);
  let found = null;
  for (const line of r.out.split('\n')) {
    const m = line.match(/^(gut|gut-local)-desktop-\d+ (.*)$/);
    if (!m) continue;
    const c = { project: m[1], running: m[2].trim() === 'running' };
    if (c.running) return c;
    found = found || c;
  }
  return found;
}

// Any HTTP answer from :8000 means the agent process is alive — the route
// deliberately doesn't matter, older daemons predate /api/version.
function probeAgent() {
  return new Promise((resolve) => {
    const req = http.get(
      { host: '127.0.0.1', port: 8000, path: '/api/version', timeout: 3000 },
      (res) => { res.resume(); resolve(true); });
    req.on('error', () => resolve(false));
    req.on('timeout', () => { req.destroy(); resolve(false); });
  });
}

// ── public API ──────────────────────────────────────────────────────────

async function status() {
  const docker = (await run('docker', ['info'])).code === 0;
  // Container state decides "running", not the HTTP probe: a wedged or
  // outdated daemon must still show Stop/Restart — that's when they're
  // needed most.
  const c = docker ? await desktopContainer() : null;
  const proj = c?.project || MANAGED;
  return {
    runtime: docker ? 'ready' : 'missing',
    stack: c?.running ? 'running' : 'stopped',
    project: proj,
    agent: c?.running ? await probeAgent() : false,
    image: proj === 'gut' ? 'dev build' : imageTag(),
    dir: proj === 'gut' ? repoDir : stackDir(),
  };
}

const INSTALL_URLS = {
  darwin: 'https://docs.docker.com/desktop/setup/install/mac-install/',
  win32: 'https://docs.docker.com/desktop/setup/install/windows-install/',
  linux: 'https://docs.docker.com/engine/install/',
};

async function installRuntime(log) {
  const brewDir = which('brew');
  if (process.platform === 'darwin' && brewDir) {
    const brew = path.join(brewDir, 'brew');
    log('Installing Colima + Docker CLI via Homebrew…');
    let r = await run(brew, ['install', 'colima', 'docker', 'docker-compose'], log);
    if (r.code !== 0) return fail('brew install failed', r);
    log('Starting Colima VM…');
    r = await run('colima', ['start', '--cpu', '4', '--memory', '8', '--disk', '60'], log);
    if (r.code !== 0) return fail('colima start failed', r);
    return { ok: (await run('docker', ['info'])).code === 0 };
  }
  // No brew (mac), or Windows/Linux: Docker Desktop / Engine is a manual
  // install — open the docs and let the user re-check.
  shell.openExternal(INSTALL_URLS[process.platform] || INSTALL_URLS.linux);
  return { ok: false, needsManual: true };
}

async function start(keys, log) {
  const env = readEnv();
  for (const k of PROVIDER_KEYS) {
    if (keys[k] && String(keys[k]).trim()) env[k] = String(keys[k]).trim();
  }
  if (!PROVIDER_KEYS.some((k) => env[k])) {
    return { ok: false, error: 'no model provider key set' };
  }
  if (DEV) {
    // The repo's compose/litellm config are the source files — persist
    // only the provider keys the user pasted, then bring the stack up.
    // Builds the desktop image from source on first run.
    const provided = {};
    for (const k of PROVIDER_KEYS) {
      if (keys[k] && String(keys[k]).trim()) provided[k] = env[k];
    }
    mergeEnv(provided);
    log('Starting the dev stack (project "gut", repo docker-compose.yml)…');
    const r = await run('docker', [...composeArgs(), 'up', '-d', '--wait'],
      log);
    if (r.code !== 0) return fail('docker compose up failed', r);
    return { ok: true, host: '127.0.0.1', password: env.GUT_PASSWORD || '' };
  }
  fs.mkdirSync(stackDir(), { recursive: true });
  if (!env.VNC_PASSWORD) {
    env.VNC_PASSWORD = rand(24);
    env.GUT_API_TOKEN = env.VNC_PASSWORD;
    env.LITELLM_MASTER_KEY = `sk-${rand(48)}`;
    env.POSTGRES_PASSWORD = rand(24);
  }
  if (!writeLitellmConfig(env)) {
    return { ok: false, error: 'no models configured' };
  }
  if (!env.DEFAULT_MODEL) {
    env.DEFAULT_MODEL = litellmConfigFirstModel(env);
  }
  writeEnv(env);
  writeCompose();

  log(`Pulling and starting the stack (image ${imageTag()}) — first run downloads several GB…`);
  const r = await run('docker', [...composeArgs(), 'up', '-d', '--wait'], log);
  if (r.code !== 0) return fail('docker compose up failed', r);
  return { ok: true, host: '127.0.0.1', password: env.VNC_PASSWORD };
}

function litellmConfigFirstModel(env) {
  for (const key of PROVIDER_KEYS) {
    if (env[key] && MODELS[key]) return MODELS[key][0][0];
  }
  return 'claude-sonnet-4-5';
}

async function stop() {
  const proj = (await desktopContainer())?.project || MANAGED;
  const r = await run('docker', [...composeArgs(proj), 'down']);
  return { ok: r.code === 0 };
}

// Bounce the stack: recreate the containers in place and wait on the
// healthchecks, like start(). Picks up .env/config changes too.
async function restart(log) {
  const proj = (await desktopContainer())?.project || MANAGED;
  if (!fs.existsSync(composeFile(proj))) {
    return { ok: false, error: 'local stack has not been created yet' };
  }
  log(`Restarting the local stack (project ${proj})…`);
  const r = await run('docker',
    [...composeArgs(proj), 'up', '-d', '--wait', '--force-recreate'], log);
  if (r.code !== 0) return fail('docker compose up failed', r);
  return { ok: true };
}

// Pull the desktop image matching this app version and recreate the stack.
// Settings → Devices offers this when the local backend runs an older tag.
async function update(log) {
  if (DEV) {
    return { ok: false, error:
      'the dev stack builds from source — rebuild with `docker compose up -d --build`' };
  }
  if (!fs.existsSync(composePath())) {
    return { ok: false, error: 'local stack has not been created yet' };
  }
  writeCompose();  // refresh the image tag for the current app version
  log(`Updating the local desktop to ${imageTag()}…`);
  let r = await run('docker', [...composeArgs(), 'pull'], log);
  if (r.code !== 0) return fail('docker compose pull failed', r);
  r = await run('docker', [...composeArgs(), 'up', '-d', '--wait'], log);
  if (r.code !== 0) return fail('docker compose up failed', r);
  return { ok: true };
}

