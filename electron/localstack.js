// Local Gut backend lifecycle for the Electron app.
//
// Packaged builds own a docker-compose stack under <userData>/local:
// generates secrets, renders litellm.yaml from the provider keys the user
// supplies, pulls the prebuilt gut-desktop image from GHCR and waits for
// it to come up. In dev (`electron .` — unpackaged) the "local backend"
// is instead the repo's own docker-compose.yml (project `gut`): the stack
// a developer runs with `docker compose up` while working on the daemon.
// Runtime install: macOS prefers Colima (free, no license limits) via brew;
// otherwise we point the user at Docker Desktop.
const { app, shell } = require('electron');
const { spawn } = require('child_process');
const crypto = require('crypto');
const fs = require('fs');
const http = require('http');
const path = require('path');

const GHCR = 'ghcr.io/valteryde/gut-desktop';
const PROVIDER_KEYS = [
  'ANTHROPIC_API_KEY', 'OPENAI_API_KEY', 'GEMINI_API_KEY',
  'DEEPSEEK_API_KEY', 'OPENROUTER_API_KEY',
];

const DEV = !app.isPackaged;
const repoDir = path.resolve(__dirname, '..');

// Two compose projects can be "the local backend": the repo's dev stack
// (`gut`, built from source — what `docker compose up` runs) and the one
// the app generates under userData (`gut-local`, prebuilt GHCR image).
// Config/key writes go to MANAGED; lifecycle commands hit whichever
// project owns the desktop container — see desktopContainer().
const MANAGED = DEV ? 'gut' : 'gut-local';

const stackDir = () => path.join(app.getPath('userData'), 'local');
const composeFile = (proj = MANAGED) => proj === 'gut'
  ? path.join(repoDir, 'docker-compose.yml')
  : path.join(stackDir(), 'compose.yaml');
const envFile = (proj = MANAGED) => proj === 'gut'
  ? path.join(repoDir, '.env')
  : path.join(stackDir(), '.env');
const envPath = () => envFile();
const composePath = () => composeFile();
const litellmPath = () => path.join(stackDir(), 'litellm.yaml');

const imageTag = () =>
  process.env.GUT_DESKTOP_IMAGE ||
  `${GHCR}:${app.isPackaged ? app.getVersion() : 'latest'}`;

// GUI apps get a bare PATH — brew/docker/colima live in /opt/homebrew or
// /usr/local on every Mac we care about.
const EXTRA_PATH = ['/opt/homebrew/bin', '/usr/local/bin', '/usr/bin', '/bin'];
const SPAWN_ENV = {
  ...process.env,
  PATH: [...(process.env.PATH || '').split(path.delimiter), ...EXTRA_PATH]
    .filter(Boolean).join(path.delimiter),
};

function run(cmd, args, onLine) {
  return new Promise((resolve) => {
    const p = spawn(cmd, args, { shell: false, env: SPAWN_ENV });
    let out = '';
    const data = (d) => {
      out += d;
      if (onLine) onLine(String(d).replace(/\n$/, ''));
    };
    p.stdout.on('data', data);
    p.stderr.on('data', data);
    p.on('error', () => resolve({ code: -1, out }));
    p.on('close', (code) => resolve({ code, out }));
  });
}

// docker compose floods progress lines; the real failure is almost always
// the last non-empty line of output.
const fail = (what, r) => {
  const tail = String(r.out).split('\n').map((l) => l.trim())
    .filter(Boolean).pop();
  return { ok: false, error: tail ? `${what}: ${tail}` : what };
};

function which(bin) {
  return SPAWN_ENV.PATH.split(path.delimiter)
    .find((d) => fs.existsSync(path.join(d, bin)));
}

// ── .env ────────────────────────────────────────────────────────────────
const rand = (n) => crypto.randomBytes(n).toString('base64url').slice(0, n);

function readEnv() {
  const env = {};
  try {
    for (const line of fs.readFileSync(envPath(), 'utf8').split('\n')) {
      const m = line.match(/^([A-Z_]+)=(.*)$/);
      if (m) env[m[1]] = m[2];
    }
  } catch (_) { /* no env yet */ }
  return env;
}

function writeEnv(env) {
  const lines = [
    '# Generated by the Gut app — edit via Settings → Provider keys.',
    `LITELLM_MASTER_KEY=${env.LITELLM_MASTER_KEY}`,
    `POSTGRES_PASSWORD=${env.POSTGRES_PASSWORD}`,
    `VNC_PASSWORD=${env.VNC_PASSWORD}`,
    `GUT_API_TOKEN=${env.GUT_API_TOKEN}`,
    `DEFAULT_MODEL=${env.DEFAULT_MODEL}`,
    'RESOLUTION=1024x768',
    'UI_SCALE=1.0',
    '',
    ...PROVIDER_KEYS.map((k) => `${k}=${env[k] || ''}`),
  ];
  fs.writeFileSync(envPath(), lines.join('\n') + '\n', { mode: 0o600 });
}

function keysSet() {
  const env = readEnv();
  return Object.fromEntries(PROVIDER_KEYS.map((k) => [k, !!env[k]]));
}

// Non-destructive .env write: update only the given KEY=VALUE lines and
// keep everything else (comments, secrets, port overrides) untouched.
// Used for the dev repo's .env, which is hand-maintained.
function mergeEnv(updates) {
  let lines = [];
  try { lines = fs.readFileSync(envPath(), 'utf8').split('\n'); }
  catch (_) { /* no env yet */ }
  const seen = new Set();
  const out = lines.map((l) => {
    const m = l.match(/^([A-Z_]+)=/);
    if (m && m[1] in updates) {
      seen.add(m[1]);
      return `${m[1]}=${updates[m[1]]}`;
    }
    return l;
  });
  for (const [k, v] of Object.entries(updates)) {
    if (!seen.has(k)) out.push(`${k}=${v}`);
  }
  fs.writeFileSync(envPath(), out.join('\n').replace(/\n*$/, '\n'),
    { mode: 0o600 });
}

// Merge provider-key edits into .env without starting the stack; an empty
// string removes the key. Once the stack has been provisioned the env file
// also carries its secrets — keep those intact and re-render the litellm
// model list so the change applies on the next `up`. Before first start
// the file holds provider lines only; start() fills in the rest.
function saveKeys(keys) {
  const updates = {};
  for (const k of PROVIDER_KEYS) {
    if (k in keys) updates[k] = String(keys[k] || '').trim();
  }
  if (DEV) {
    mergeEnv(updates);
    return keysSet();
  }
  fs.mkdirSync(stackDir(), { recursive: true });
  const env = readEnv();
  Object.assign(env, updates);
  if (env.VNC_PASSWORD) {
    writeEnv(env);
    writeLitellmConfig(env);
  } else {
    const lines = [
      '# Provider keys saved from Settings — the app fills in the rest on first start.',
      ...PROVIDER_KEYS.map((k) => `${k}=${env[k] || ''}`),
    ];
    fs.writeFileSync(envPath(), lines.join('\n') + '\n', { mode: 0o600 });
  }
  return keysSet();
}

